package org.us_ignite.thingworx.dap;

/** ThingWorx base types supported by the declarative entity generator. */
public enum DapBaseType {
    /** Boolean value. */
    BOOLEAN,
    /** Date and time value. */
    DATETIME,
    /** InfoTable value. */
    INFOTABLE,
    /** Integer value. */
    INTEGER,
    /** Password value. */
    PASSWORD,
    /** String value. */
    STRING,
    /** Thing name value. */
    THINGNAME
}
