import {LitElement} from 'lit';
import {L2Pw} from 'ptcs-library/library-lit';
import {PTCS} from 'ptcs-library/library.js';
import 'ptcs-label/ptcs-label.js';
import 'ptcs-checkbox/ptcs-checkbox.js';
import 'ptcs-radio/ptcs-radio.js';
import 'ptcs-link/ptcs-link.js';
import 'ptcs-behavior-tooltip/ptcs-behavior-tooltip.js';
import 'ptcs-behavior-styleable/ptcs-behavior-styleable.js';

PTCS.ListItem = class extends PTCS.BehaviorTooltip(PTCS.BehaviorStyleable(L2Pw(LitElement))) {
    static get is() {
        return 'ptcs-list-item';
    }

    static get properties() {
        return {
            label: {
                type:     String,
                observer: '_labelChanged'
            },

            hint: {
                type: String
            },

            labelMeta: {
                type:      String,
                attribute: 'label-meta',
                observer:  '_labelMetaChanged'
            },

            itemMeta: {
                type:      Object,
                attribute: 'item-meta',
                observer:  '_itemMetaChanged'
            },

            alignment: { // 'left', 'center', 'right'
                type:     String,
                observer: '_alignmentChanged'
            },

            selected: {
                type:     Boolean,
                notify:   true,
                reflect:  true,
                observer: '_selectedChanged'
            },

            disabled: {
                type:     Boolean,
                reflect:  true,
                observer: '_disabledChanged'
            },

            multiSelect: {
                type:      Boolean,
                attribute: 'multi-select',
                observer:  '_multiSelectChanged'
            },

            radioButtonSelection: {
                type:      Boolean,
                attribute: 'radio-button-selection',
                observer:  '_radioButtonSelectionChanged'
            },

            multiLine: {
                type:      Boolean,
                attribute: 'multi-line',
                observer:  '_multiLineChanged'
            },

            // Tooltip data provided by list owner (like a dropdown) to be shown during list item truncation tooltip
            ownerTooltip: {
                type:      String,
                attribute: 'owner-tooltip'
            },

            ownerTooltipIcon: {
                type:      String,
                attribute: 'owner-tooltip-icon'
            },

            itemValue: {
                type:      String,
                attribute: 'item-value'
            },

            // ARIA

            ariaDisabled: {
                type:      String,
                attribute: 'aria-disabled',
                computed:  '_compute_ariaDisabled(disabled)',
                reflect:   true
            },

            ariaLabel: {
                type:      String,
                attribute: 'aria-label',
                computed:  '_computeAriaLabel(label, tooltip)',
                reflect:   true
            },


            ariaSelected: {
                type:      String,
                attribute: 'aria-selected',
                computed:  '_compute_ariaSelected(selected)',
                reflect:   true
            },

            role: {
                type:    String,
                reflect: true
            }
        };
    }

    createRenderRoot() {
        return this;
    }

    constructor() {
        super();

        // Default values
        this.alignment = 'left';
        this.itemValue = 'item-value';
        this.role = 'option';
    }

    ready() {
        super.ready();
        this.tooltipFunc = this._monitorTooltip;
        this.addEventListener('click', (e) => {
            if (this.disabled) {
                e.stopPropagation();
                return;
            }

            if (this.selected) {
                if (this.multiSelect) {
                    this.selected = false;
                }
            } else {
                this.selected = true;
            }
        });
    }

    _monitorTooltip() {
        const containerEl = this.querySelector(`[part~=${this.itemValue}]`);
        if (!this.disableTooltip && containerEl && containerEl.firstChild) {
            const itemLabel = containerEl.firstChild;
            if (typeof itemLabel.isTruncated === 'function' && itemLabel.isTruncated()) {
                // Truncated list item returns the label text when truncated and has no own tooltip: Return owner tooltip as tooltip
                itemLabel.tooltip = this.ownerTooltip;
                // When hovering above list item, the tooltip is generated by ptcs-list-item along the edges and by ptcs-label above the text
                itemLabel.tooltipIcon = this.ownerTooltipIcon; // For ptcs-label tooltip
                this.tooltipIcon = this.ownerTooltipIcon; // For ptcs-list-item tooltip
            } else {
                // Clear the tooltip that may have been previously assigned, we should only show tooltip on list item when truncated
                itemLabel.tooltip = undefined;
            }
            if (typeof itemLabel.tooltipFunc === 'function') {
                return itemLabel.tooltipFunc();
            }
        }
        return '';
    }

    // Set boolean attribute
    _setbattr(el, attr, value) {
        if (!el) {
            return;
        }

        if (value) {
            el.setAttribute(attr, '');
        } else {
            el.removeAttribute(attr);
        }
    }

    // Set value attribute
    _setvattr(el, attr, value) {
        if (value) {
            el.setAttribute(attr, value);
        } else {
            el.removeAttribute(attr);
        }
    }

    // Get item type
    _type() {
        if (this.hint === this.label) {
            return 'text';
        }
        return this.itemMeta ? this.itemMeta.type : 'text';
    }

    _getCheckbox() {
        let el = this.querySelector('[part=item-checkbox]');

        if (!el && this.multiSelect) {

            el = document.createElement('ptcs-checkbox');
            el.setAttribute('part', 'item-checkbox');
            // remove default tabindex
            el.noTabindex = true;
            el.checked = this.selected;
            el.disabled = this.disabled;

            el.addEventListener('checked-changed', ev => {
                this.selected = ev.detail.value;
            });

            el.addEventListener('click', ev => {
                ev.stopPropagation();
            });

            this.appendChild(el);
        }

        return el;
    }

    _getRadio() {
        let el = this.querySelector('[part=item-radio]');

        if (!el && this.radioButtonSelection) {
            el = document.createElement('ptcs-radio');
            el.setAttribute('part', 'item-radio');
            el.label = '';
            // remove default tabindex
            el.noTabindex = true;
            el.checked = this.selected;
            el.disabled = this.disabled;

            el.addEventListener('checked-changed', ev => {
                this.selected = ev.detail.value;
            });

            el.addEventListener('click', ev => {
                ev.stopPropagation();
            });

            this.appendChild(el);
        }

        return el;
    }

    _createItem(type) {
        if (this.label === this.hint) {
            type = 'text';
        }
        let el;
        let needsStateFormatting = false;

        switch (type) {
            case undefined: // Default to 'text'
            case 'text':
                el = document.createElement('ptcs-label');
                el.setAttribute('variant', 'list-item');
                if (this.disableTooltip) {
                    el.setAttribute('disable-tooltip', '');
                }
                needsStateFormatting = true;

                if (this.label) {
                    el.label = this.label;
                }
                if (this.disabled) {
                    el.setAttribute('disabled', '');
                }
                el.multiLine = this.multiLine;
                break;

            case 'link':
                el = document.createElement('ptcs-link');
                el.setAttribute('variant', 'primary');
                // remove default tabindex
                el.noTabindex = true;
                if (this.disableTooltip) {
                    el.setAttribute('disable-tooltip', '');
                }
                needsStateFormatting = true;

                if (this.label.href) {
                    el.setAttribute('href', encodeURI(this.label.href));
                }
                if (this.disabled) {
                    el.setAttribute('disabled', '');
                }
                if (this.label.label || this.itemMeta.label) {
                    el.label = this.label.label || this.itemMeta.label;
                }
                if (this.itemMeta.target) {
                    el.setAttribute('target', this.itemMeta.target);
                }
                break;

            case 'image':
                el = document.createElement('img');

                needsStateFormatting = true;

                if (this.label) {
                    el.setAttribute('src', this.label);
                }
                if (this.disabled) {
                    el.setAttribute('disabled', '');
                }
                if (this.itemMeta.width) {
                    el.style.width = this.itemMeta.width;
                }
                if (this.itemMeta.height) {
                    el.style.height = this.itemMeta.height;
                }
                break;

            case 'checkbox':
                el = document.createElement('ptcs-checkbox');

                needsStateFormatting = true;

                el.checked = this.label ? (this.label !== 'false') : false;
                el.setAttribute('disabled', '');
                // remove default tabindex
                el.noTabindex = true;
                break;

            case 'html':
                el = document.createElement('span');
                if (this.label) {
                    el.innerHTML = this.label;
                }
                if (this.disabled) {
                    el.setAttribute('disabled', '');
                }
                break;

            case 'function':
                if (this.label) {
                    el = this.label(this.disabled);
                }
                break;

            default:
                throw Error(`Unknown list item type: ${type}`);
        }

        const containerEl = document.createElement('ptcs-div');
        containerEl.setAttribute('part', `${this.itemValue}${needsStateFormatting ? ' state-value' : ''}`);

        containerEl.__type = type;

        if (this.selected) {
            containerEl.setAttribute('selected', '');
        }
        if (this.alignment) {
            this._setAlignment(containerEl, this.alignment);
        }
        if (el) {
            containerEl.appendChild(el);
            this.__stateValueEl = (containerEl.getAttribute('part').includes('state-value')) ? containerEl : undefined;
        }
        return containerEl;
    }

    _getItem() {
        let el = this.querySelector(`[part~=${this.itemValue}]`);

        if (!el) {
            el = this._createItem(this._type());

            this.appendChild(el);
        }

        return el;
    }

    _getInternalItem() {
        const el = this._getItem();
        if (el && el.firstChild) {
            return el.firstChild;
        }

        return null;
    }

    _getMeta() {
        let el = this.querySelector('[part=item-meta]');

        if (!el && this.labelMeta) {

            el = document.createElement('ptcs-label');
            el.setAttribute('part', 'item-meta');
            if (!this.labelMeta) {
                el.setAttribute('hidden', '');
            }

            if (this.disabled) {
                el.setAttribute('disabled', '');
            }

            el.label = this.labelMeta;
            el.multiLine = this.multiLine;
            el.horizontalAlignment = this.alignment;
            this.appendChild(el);
        }

        return el;
    }

    _itemMetaChanged(itemMeta) {
        if (this.label === this.hint) {
            return; // ignore type modification for the hint
        }

        this._itemMetaTypeChanged(this._type());
    }

    _itemMetaTypeChanged(type) {
        const el = this._getItem();

        if (el.__type !== type) {
            const el2 = this._createItem(type);
            el.parentNode.insertBefore(el2, el);
            el.parentNode.removeChild(el);
        } else {
            // Ugly hack to fix link label update. This needs a more solid fix for all meta properties.
            switch (type) {
                case 'link':
                    el.firstElementChild.label = this.label.label || this.itemMeta.label;
                    break;
            }
        }
    }

    _labelChanged(label) {
        const type = this._type();

        let el = this._getItem();

        if (el.__type !== type || type === 'function') {
            const el2 = this._createItem(type);
            el.parentNode.insertBefore(el2, el);
            el.parentNode.removeChild(el);
            return;
        }

        el = this._getInternalItem();
        switch (type) {
            case 'text':
                el.label = label;
                break;

            case 'link':
                this._setvattr(el, 'href', encodeURI(label.href));
                this._setvattr(el, 'label', label.label);
                break;

            case 'checkbox':
                el.checked = label ? (this.label !== 'false') : false;
                break;

            case 'image':
                this._setvattr(el, 'src', label);
                break;

            case 'html':
                el.innerHTML = label;
                break;
        }
    }

    _labelMetaChanged(labelMeta) {
        const el = this._getMeta();

        if (!el) {
            return;
        }

        // Has visibiliy changed?
        if (!labelMeta !== !el.label) {
            this._setbattr(el, 'hidden', !labelMeta);
        }

        // Update label
        el.label = labelMeta;
    }

    _multiSelectChanged(multiSelect) {
        if (multiSelect) {
            // Request multiselect checkbox, to make sure it is created
            this._getCheckbox();
        }
    }

    _radioButtonSelectionChanged(radioButtonSelection) {
        if (radioButtonSelection) {
            this._getRadio();
        }
    }

    _multiLineChanged(multiLine) {
        const type = this._type();
        const el = this._getMeta();

        if (el) {
            el.multiLine = multiLine;
        }

        if (type === 'text') {
            this._getInternalItem().multiLine = multiLine;
        }
    }

    _alignmentChanged(alignment) {
        const el = this._getItem();
        this._setAlignment(el, alignment);
    }

    _setAlignment(el, alignment) {
        switch (alignment) {
            case 'left':
                el.style.justifyContent = 'flex-start';
                break;
            case 'right':
                el.style.justifyContent = 'flex-end';
                break;
            case 'center':
                el.style.justifyContent = 'center';
                break;
            default:
                el.style.justifyContent = 'flex-start'; // behaves as left
        }

        el = this._getMeta();
        if (el) {
            el.horizontalAlignment = this.alignment;
        }
    }

    _selectedChanged(selected) {
        const el = this.multiSelect ? this._getCheckbox() : this._getRadio();
        if (el) {
            el.checked = selected;
        }

        this._setbattr(this._getItem(), 'selected', selected);
    }

    _disabledChanged(disabled) {
        const type = this._type();
        const el = this.multiSelect ? this._getCheckbox() : this._getRadio();
        if (el) {
            el.disabled = disabled;
        }

        // Update item
        switch (type) {
            case 'text':
            case 'link':
            case 'image':
            case 'html':
                this._setbattr(this._getItem(), 'disabled', disabled);
                this._setbattr(this._getInternalItem(), 'disabled', disabled);
                this._setbattr(this._getMeta(), 'disabled', disabled);
                break;
            case 'function': {
                this._setbattr(this._getItem(), 'disabled', disabled);
                const linkEls = this.querySelectorAll('ptcs-link');
                _.forEach(linkEls, linkEl => {
                    linkEl.disabled = disabled;
                });
                break;
            }
        }
    }

    // ARIA attributes

    _compute_ariaDisabled(disabled) {
        return disabled ? 'true' : undefined;
    }

    _computeAriaLabel(label, tooltip) {
        return label || tooltip;
    }

    _compute_ariaSelected(selected) {
        return selected ? 'true' : undefined;
    }

    // Get auto width of item
    get autoWidth() {
        const cb = this.multiSelect && this.querySelector('[part=item-checkbox]');
        const el = this._getInternalItem();
        return (cb ? cb.offsetWidth : 0) + (el ? el.offsetWidth : 0);
    }
};

customElements.define(PTCS.ListItem.is, PTCS.ListItem);
